// Converts the 18xx Maker prototype (design/TwoCrowns1874.json) into src/generated/*.ts.
// Run with `pnpm import`; `pnpm import:watch` reruns it and rebuilds the package whenever the
// design folder changes, so a running harness picks up the new data on reload.
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(root, 'design', 'TwoCrowns1874.json')
const outDir = join(root, 'src', 'generated')
const header =
    '// Generated by scripts/import-maker.mjs from design/TwoCrowns1874.json. Do not edit.\n'

// 18xx Maker's named colours used by the prototype; the file's own `colors` override them.
const MakerPalette = {
    black: '#2b2b2b',
    blue: '#0189d1',
    brightGreen: '#68b34a',
    cherry: '#a3122f',
    fuchsia: '#c2187e',
    gold: '#d4af37',
    gray: '#8c8c8c',
    lavender: '#b39ddb',
    lightBlue: '#7fc6e8',
    lightBrown: '#b9875f',
    lime: '#b5d334',
    navyBlue: '#1d3d7a',
    orange: '#f48221',
    pink: '#f08fb5',
    red: '#d81e3e',
    violet: '#7b52a3',
    white: '#ffffff',
    yellow: '#ffd331'
}

// Hex labels that select upgrade tiles, by the colour from which each applies (1874design.md, Map).
const UpgradeLabels = {
    X: [{ color: 'yellow', label: 'X' }],
    CX: [
        { color: 'yellow', label: 'X' },
        { color: 'gray', label: 'CX' }
    ],
    P: [
        { color: 'yellow', label: 'X' },
        { color: 'brown', label: 'P' }
    ],
    J: [{ color: 'brown', label: 'J' }],
    S: [{ color: 'green', label: 'S' }]
}

const game = JSON.parse(readFileSync(source, 'utf8'))
const colors = { ...MakerPalette, ...game.colors }
const phaseTileColor = Object.fromEntries(
    game.phases.map((phase) => [`phase${phase.train.toLowerCase()}`, phase.tiles])
)
const preprintedLabels = new Set(
    Object.values(game.tiles).flatMap((tile) =>
        typeof tile === 'object' ? (tile.labels ?? []).map((label) => label.label) : []
    )
)

const edge = (side) => side - 1
const turns = { sharp: 1, gentle: 2, straight: 3 }
const ascii = (text) => text.normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/Đ/g, 'D')
const slug = (text) =>
    ascii(text)
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
const literal = (value) => JSON.stringify(value)

function trackPaths(track) {
    return track
        .filter((entry) => turns[entry.type])
        .map((entry) => [edge(entry.side), (edge(entry.side) + turns[entry.type]) % 6])
}
function nodeEdges(track) {
    return track.filter((entry) => !entry.type).map((entry) => edge(entry.side))
}
function offboardEdges(track) {
    return track.filter((entry) => entry.type === 'offboard').map((entry) => edge(entry.side))
}
function stagedRevenue(revenues) {
    const stages = revenues.map((entry) => [phaseTileColor[entry.color], Number(entry.cost)])
    if (stages.some(([stage]) => !stage))
        throw new Error(`Unknown revenue phase in ${literal(revenues)}`)
    return `revenue(${literal(stages)})`
}
function tileLabels(labels) {
    return (labels ?? []).map((entry) => entry.label).filter((label) => preprintedLabels.has(label))
}
function hexLabels(labels) {
    return (labels ?? []).map((entry) => entry.label).filter((label) => UpgradeLabels[label])
}
function hexColor(color) {
    const mapped = { plain: 'white', offboard: 'red', water: 'blue' }[color] ?? color
    if (!['white', 'yellow', 'green', 'brown', 'gray', 'red', 'blue'].includes(mapped))
        throw new Error(`Unknown hex colour ${color}`)
    return mapped
}
function value(hex) {
    return hex.values?.[0]?.value ?? 0
}

function hexFace(hex, color) {
    const track = hex.track ?? []
    if (hex.color === 'offboard') {
        if (hex.cities?.length)
            return `city('red', ${literal(nodeEdges(track))}, ${stagedRevenue(hex.offBoardRevenue.revenues)}, 0)`
        return `offboard(${literal(offboardEdges(track))}, ${stagedRevenue(hex.offBoardRevenue.revenues)})`
    }
    if (hex.cities?.length) {
        if (hex.cities.length > 1)
            throw new Error(`Multi-city map hexes are not supported: ${hex.hexes}`)
        const labels = tileLabels(hex.labels)
        return `city(${literal(color)}, ${literal(nodeEdges(track))}, ${value(hex)}, ${hex.cities[0].size ?? 1}${labels.length ? `, ${literal(labels)}` : ''})`
    }
    if (hex.centerTowns?.length) {
        const edges = nodeEdges(track)
        const towns = hex.centerTowns.length === 1 ? [edges] : hex.centerTowns.map(() => [])
        if (hex.centerTowns.length > 1 && edges.length)
            throw new Error(`Tracked double towns are not supported: ${hex.hexes}`)
        return `town(${literal(color)}, ${literal(towns)}, ${value(hex)})`
    }
    return `track(${literal(color)}, ${literal(trackPaths(track))})`
}

function hexDetails(hex) {
    const details = {}
    if (hex.terrain?.length) {
        details.terrain = {
            cost: Math.max(...hex.terrain.map((terrain) => terrain.cost)),
            kinds: [...new Set(hex.terrain.map((terrain) => terrain.type))]
        }
    }
    const labels = hexLabels(hex.labels).filter(() => hex.color === 'plain')
    if (labels.length > 1) throw new Error(`Several upgrade labels on ${hex.hexes}`)
    if (labels.length) details.upgradeLabels = UpgradeLabels[labels[0]]
    return details
}

function hexName(hex) {
    const names = [...(hex.cities ?? []), ...(hex.centerTowns ?? [])]
        .map((stop) => stop.name?.name)
        .filter(Boolean)
    if (names.length) return names.join(' & ')
    return hex.offBoardRevenue?.name?.name
}

function mapModule() {
    const names = {}
    const homes = {}
    const offboardHexes = {}
    const lines = []
    for (const hex of game.map.hexes) {
        const name = hexName(hex)
        for (const id of hex.hexes) {
            if (name) names[id] = name
            const home = hex.cities?.[0]?.companies?.[0]
            if (typeof home === 'string') homes[id] = home
            if (hex.color === 'offboard' && name) (offboardHexes[name] ??= []).push(id)
        }
    }
    const stopGroups = Object.fromEntries(
        Object.entries(offboardHexes)
            .filter(([, ids]) => ids.length > 1)
            .flatMap(([name, ids]) => ids.map((id) => [id, slug(name)]))
    )
    for (const hex of game.map.hexes) {
        const color = hexColor(hex.color)
        const face = hexFace(hex, color)
        const details = hexDetails(hex)
        const grouped = Object.groupBy(hex.hexes, (id) => stopGroups[id] ?? '')
        for (const [group, ids] of Object.entries(grouped)) {
            const extra = group ? { ...details, stopGroup: group } : details
            const suffix = Object.keys(extra).length ? `, ${literal(extra)}` : ''
            lines.push(`...locations(${literal(ids.join(' '))}, ${face}${suffix}),`)
        }
    }
    return `${header}import { HexOrientation } from '@tabletop/common'
import {
    createLetterNumberLocationFactory,
    createStagedTileRevenue as revenue,
    createTrackTileFace as track,
    createTownTileFace as town,
    createCityTileFace as city,
    createOffboardTileFace as offboard,
    type MapLocation
} from '@tabletop/18xx'

export const TwoCrownsLocationNames: Readonly<Record<string, string>> = ${literal(names)}

export const TwoCrownsHomes: Readonly<Record<string, string>> = ${literal(homes)}

export function twoCrownsLocations(
    markers: Readonly<Record<string, NonNullable<MapLocation['markers']>>>
): MapLocation[] {
    const locations = createLetterNumberLocationFactory({
        orientation: HexOrientation.Flat,
        numberOffset: 1,
        fixedColors: ['gray', 'blue', 'red'],
        names: TwoCrownsLocationNames,
        homes: TwoCrownsHomes,
        markers
    })
    return [
        ${lines.join('\n        ')}
    ]
}
`
}

function tileFace(id, tile) {
    const labels = tileLabels(tile.labels)
    const track = tile.track ?? []
    if ((tile.cities?.length ?? 0) > 1) {
        const paths = track.map((entry) => [
            edge(entry.side),
            (edge(entry.side) + turns[entry.type]) % 6
        ])
        if (paths.length !== tile.cities.length || paths.some(([, b]) => Number.isNaN(b)))
            throw new Error(`Tile ${id}: each city needs one typed track`)
        const cities = paths.map((edges, index) => ({
            edges,
            revenue: tile.values[index].value,
            stationSlots: tile.cities[index].size ?? 1
        }))
        return `createSeparateCitiesTileFace(${literal(tile.color)}, ${literal(cities)}, ${literal(labels)})`
    }
    const edges = track.map((entry) => edge(entry.side))
    return `createCityTileFace(${literal(tile.color)}, ${literal(edges)}, ${value(tile)}, ${tile.cities?.[0]?.size ?? 1}, ${literal(labels)})`
}

function tilesModule() {
    const shared = {}
    const special = []
    for (const [id, tile] of Object.entries(game.tiles)) {
        if (typeof tile === 'number') shared[id] = tile
        else {
            if (!tile.cities?.length)
                throw new Error(`Tile ${id}: only city specials are supported`)
            special.push({ id, count: tile.quantity ?? 1, face: tileFace(id, tile) })
        }
    }
    const definitions = special
        .map(
            (tile) => `{
        id: 'two-crowns:${tile.id}',
        printedNumber: '${tile.id}',
        aliases: [],
        scope: 'The Two Crowns 1874',
        face: ${tile.face}
    }`
        )
        .join(',\n    ')
    return `${header}import {
    createCityTileFace,
    createSeparateCitiesTileFace,
    type TileDefinition,
    type TileManifestEntry
} from '@tabletop/18xx'

export const TwoCrownsSharedTileCounts: Readonly<Record<string, TileManifestEntry['count']>> = ${literal(shared)}

export const TwoCrownsSpecialTiles: readonly TileDefinition[] = [
    ${definitions}
]

export const TwoCrownsSpecialTileCounts: Readonly<Record<string, TileManifestEntry['count']>> = ${literal(Object.fromEntries(special.map((tile) => [tile.id, tile.count])))}
`
}

function marketRows() {
    return game.stock.market.map((row) => {
        const cells = row.map((cell) =>
            cell === null
                ? null
                : typeof cell === 'number'
                  ? cell
                  : typeof (cell.value ?? cell.label) === 'number'
                    ? (cell.value ?? cell.label)
                    : null
        )
        const first = cells.findIndex((cell) => cell !== null)
        const end = cells.findIndex((cell, index) => index > first && cell === null)
        return cells.slice(0, end === -1 ? cells.length : end)
    })
}

function parCells() {
    const cells = {}
    game.stock.market.forEach((row, rowIndex) =>
        row.forEach((cell, column) => {
            if (cell && typeof cell === 'object' && cell.par)
                cells[cell.color] = `${rowIndex}:${column}`
        })
    )
    return cells
}

function dataModule() {
    const luka = game.companies.filter((company) => company.subtext === 'Luka')
    const branches = game.companies.filter((company) => company.subtext === 'Branch')
    const color = (company) => colors[company.color] ?? company.color
    // Luka share numbers come from the share labels ("#1 Split"), as on 1871's PEIR shares.
    const lukaNumbers = new Map(
        game.companies
            .find((company) => company.abbrev === 'LUKA')
            .shares.map((share) => /^#(\d+) (.+)$/.exec(share.label))
            .map((match) => [match[2], Number(match[1])])
    )
    const companies = luka.map((company) => {
        const number = lukaNumbers.get(company.name)
        if (!number) throw new Error(`No Luka share is labelled for ${company.name}`)
        return { companyId: company.abbrev, name: company.name, number, color: color(company) }
    })
    const branchData = branches.map((company) => ({
        id: `branch:${ascii(company.abbrev)}`,
        name: company.name,
        label: company.abbrev,
        color: color(company)
    }))
    const privates = game.privates.map((item) => ({
        id: item.id,
        name: item.name,
        faceValue: item.price ?? 0,
        revenue: item.revenue ?? 0,
        description: item.description,
        ...(item.minPlayers ? { minPlayers: item.minPlayers } : {}),
        ...(item.maxPlayers ? { maxPlayers: item.maxPlayers } : {})
    }))
    const trains = game.trains.map((train) => ({
        id: train.name,
        price: train.price,
        count: train.quantity,
        ...(train.rust ? { rustsOn: train.rust } : {})
    }))
    const phases = game.phases.map((phase) => ({
        id: phase.train,
        tileColor: phase.tiles,
        operatingRounds: phase.rounds,
        trainLimit: phase.limit
    }))
    const players = game.players.map((player) => ({
        count: player.number,
        certificateLimit: player.certLimit,
        startingCash: player.capital
    }))
    return `${header}
export const TwoCrownsTitle = ${literal({ name: game.info.title, designer: game.info.designer })}

export const TwoCrownsLukaCompanies = ${literal(companies)} as const

export const TwoCrownsBranchCompanies = ${literal(branchData)} as const

export const TwoCrownsPrivateData = ${literal(privates)} as const

export const TwoCrownsMarketRows: readonly (readonly (number | null)[])[] = ${literal(marketRows())}

export const TwoCrownsParCells: Readonly<Record<string, string>> = ${literal(parCells())}

export const TwoCrownsTrainData = ${literal(trains)} as const

export const TwoCrownsPhaseData = ${literal(phases)} as const

export const TwoCrownsPlayerData = ${literal(players)} as const
`
}

// design.ts stamps the build with the design version (from design/SOURCE.json, written by
// scripts/sync-design.mjs) and short hashes of the generated modules, so bot runs can record
// which map, tiles and data they played.
function designModule(modules) {
    const sourcePath = join(root, 'design', 'SOURCE.json')
    const source = existsSync(sourcePath)
        ? JSON.parse(readFileSync(sourcePath, 'utf8'))
        : { version: 'unsynced', commit: '', dirty: true }
    const hash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 8)
    // A copy changed since the last sync (by hand, or by sync-to-tabletop.ps1) no longer matches
    // its recorded commit, so the build is marked dirty.
    const copied = Object.entries(source.files ?? {}).every(
        ([file, sha]) =>
            createHash('sha256')
                .update(readFileSync(join(root, 'design', file)))
                .digest('hex')
                .slice(0, 12) === sha
    )
    const design = {
        version: source.version,
        commit: source.commit,
        dirty: source.dirty || !source.files || !copied,
        mapHash: hash(modules['map.ts']),
        tilesHash: hash(modules['tiles.ts']),
        dataHash: hash(modules['data.ts'])
    }
    return `${header}export const TwoCrownsDesign = ${literal(design)} as const
`
}

mkdirSync(outDir, { recursive: true })
const outputs = { 'map.ts': mapModule(), 'tiles.ts': tilesModule(), 'data.ts': dataModule() }
outputs['design.ts'] = designModule(outputs)
for (const [file, contents] of Object.entries(outputs)) writeFileSync(join(outDir, file), contents)
execFileSync('pnpm', ['exec', 'prettier', '--write', '--log-level', 'warn', outDir], {
    cwd: root,
    stdio: 'inherit'
})
console.log(`Imported ${source} into ${outDir}`)
if (process.argv.includes('--build')) {
    execFileSync('pnpm', ['run', 'build'], { cwd: root, stdio: 'inherit' })
    console.log(`Rebuilt @tabletop/two-crowns at ${new Date().toLocaleTimeString()}`)
}
