// Renders the player rulebook the design sync copied to ../two-crowns/design/1874rules.md into
// src/lib/rules/rulebook.ts, which the table's rules button opens. `pnpm sync` in
// @tabletop/two-crowns runs it; run it by hand with `node scripts/rulebook.mjs`.
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Marked } from 'marked'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const designFolder = join(root, '..', 'two-crowns', 'design')
const source = JSON.parse(readFileSync(join(designFolder, 'SOURCE.json'), 'utf8'))
// The rulebook opens with a note for the designer (generated, the design draft wins); players
// see the rules from the title on.
const markdown = readFileSync(join(designFolder, '1874rules.md'), 'utf8').replace(
    /^> \*\*Generated, not authoritative\.\*\*.*\n+/,
    ''
)

const plain = (text) => text.replace(/\*\*|__|\*|_/g, '').trim()
// The headings are in capitals; the contents list them in sentence case ("1 Introduction").
const sentence = (text) =>
    text
        .toLowerCase()
        .replace(/^(\d+\s+)?([a-z])/, (_, number = '', letter) => number + letter.toUpperCase())
const slug = (text) =>
    plain(text)
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '')
const contents = []
const marked = new Marked({
    renderer: {
        heading({ tokens, depth, text }) {
            const id = `rule-${slug(text)}`
            if (depth === 1) contents.push({ id, title: sentence(plain(text)) })
            return `<h${depth} id="${id}">${this.parser.parseInline(tokens)}</h${depth}>\n`
        },
        link({ href, tokens }) {
            return `<a href="${href}" target="_blank" rel="noopener noreferrer">${this.parser.parseInline(tokens)}</a>`
        }
    }
})
const html = marked.parse(markdown, { async: false })

// With --doc <file>, writes the rulebook as one HTML page for Drive to turn into a Google Doc
// instead: marks become highlighting, and the cards load from the public tabletop fork, where
// the release has pushed them.
const docAt = process.argv.indexOf('--doc')
if (docAt !== -1) {
    const docOut = process.argv[docAt + 1]
    if (!docOut) throw new Error('Usage: node scripts/rulebook.mjs --doc <out.html>')
    const cardsUrl =
        'https://raw.githubusercontent.com/Suhar/tabletop/two-crowns/games/two-crowns-ui/src/lib/rules/cards/'
    const doc = html
        .replace(/<mark>/g, '<span style="background-color:#fff2cc">')
        .replace(/<\/mark>/g, '</span>')
        .replace(/src="cards\//g, `src="${cardsUrl}`)
        .replace(/<table>/g, '<table style="border-collapse:collapse" border="1" cellpadding="4">')
        .replace(/ id="[^"]*"/g, '')
    writeFileSync(
        docOut,
        `<!DOCTYPE html>\n<html><head><meta charset="utf-8"><title>The Two Crowns 1874 — Rules v${source.version}</title></head>\n` +
            `<body style="font-family:Arial,sans-serif">\n${doc}</body></html>\n`
    )
    console.log(`Wrote the ${source.version} rulebook for a Google Doc to ${docOut}`)
    process.exit(0)
}

// The private company cards (<img src="cards/P1.png">) are bundled as assets beside the module,
// which puts each one's built URL in its place.
const cardsOut = join(root, 'src', 'lib', 'rules', 'cards')
rmSync(cardsOut, { recursive: true, force: true })
mkdirSync(cardsOut)
const cards = [
    ...new Set([...html.matchAll(/src="cards\/([\w-]+\.png)"/g)].map((match) => match[1]))
]
for (const card of cards) copyFileSync(join(designFolder, 'cards', card), join(cardsOut, card))
const cardName = (card) => `card${card.replace(/\.png$/, '').replace(/-/g, '_')}`

const literal = (value) => JSON.stringify(value)
const out = join(root, 'src', 'lib', 'rules', 'rulebook.ts')
writeFileSync(
    out,
    `// Generated by scripts/rulebook.mjs from the design's rulebook. Do not edit.\n` +
        cards.map((card) => `import ${cardName(card)} from './cards/${card}'\n`).join('') +
        `const Cards: Readonly<Record<string, string>> = { ${cards
            .map((card) => `${literal(card)}: ${cardName(card)}`)
            .join(', ')} }\n` +
        `export const RulebookVersion = ${literal(source.version)}\n` +
        `export const RulebookContents: readonly { id: string; title: string }[] = ${literal(contents)}\n` +
        `export const RulebookHtml = ${literal(html)}.replace(\n` +
        `    /src="cards\\/([\\w-]+\\.png)"/g,\n` +
        `    (_, card: string) => \`src="\${Cards[card]}" loading="lazy"\`\n` +
        `)\n`
)
execFileSync('pnpm', ['exec', 'prettier', '--write', '--log-level', 'warn', out], {
    cwd: root,
    stdio: 'inherit'
})
console.log(`Rendered the ${source.version} rulebook: ${contents.length} sections`)
